import test from 'node:test';
import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {loadEntries} from '../src/content';
import {entryUrl} from '../src/model';
import {RealFunctionsV1Directory,realFunctionsV1Chapters,realFunctionsV1Url} from '../src/RealFunctionsV1Directory';
import {MathNavigation,StudyDirectory} from '../src/StudyDirectory';
import {Article} from '../src/components';

test('v1 keeps the 31-section framework, distinguishes pending sections, and preserves original course navigation',async()=>{
  const items=await loadEntries(new URL('../content/',import.meta.url).pathname);
  const entry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch01-s1.md')!;
  assert.ok(entry);
  assert.equal(entry.mathFont,'cm-bea');
  assert.equal(entry.attachmentPath,'notes/real-functions-v1/real-functions-v1-1-1.pdf');
  assert.deepEqual(realFunctionsV1Chapters.map(c=>c.sections.length),[5,5,3,5,4,5,4]);
  const html=renderToStaticMarkup(createElement(RealFunctionsV1Directory,{items}));
  assert.equal((html.match(/id="section-/g)||[]).length,31);
  assert.equal((html.match(/待编写/g)||[]).length,24);
  assert.ok(html.includes(`href="${entryUrl(entry)}/"`));
  const nextEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch01-s2.md')!;
  assert.ok(nextEntry);
  assert.equal(nextEntry.mathFont,'cm-bea');
  assert.equal(nextEntry.attachmentPath,'notes/real-functions-v1/real-functions-v1-1-2.pdf');
  assert.ok(html.includes(`href="${entryUrl(nextEntry)}/"`));
  assert.ok(html.includes('href="#section-2-3"'));
  assert.ok(html.includes('href="/math/real-functions/"'));
  const thirdEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch01-s3.md')!;
  assert.ok(thirdEntry);
  assert.ok(html.includes(`href="${entryUrl(thirdEntry)}/"`));
  const fourthEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch01-s4.md')!;
  assert.ok(fourthEntry);
  assert.equal(fourthEntry.mathFont,'cm-bea');
  assert.equal(fourthEntry.attachmentPath,'notes/real-functions-v1/real-functions-v1-1-4.pdf');
  assert.ok(html.includes(`href="${entryUrl(fourthEntry)}/"`));
  const fifthEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch01-s5.md')!;
  assert.ok(fifthEntry);
  assert.equal(fifthEntry.mathFont,'cm-bea');
  assert.equal(fifthEntry.attachmentPath,'notes/real-functions-v1/real-functions-v1-1-5.pdf');
  assert.ok(html.includes(`href="${entryUrl(fifthEntry)}/"`));
  const fifthArticle=renderToStaticMarkup(createElement(Article,{entry:fifthEntry,items}));
  assert.doesNotMatch(fifthArticle,/katex-error/);
  const fifthIds=new Set([...fifthArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of fifthArticle.matchAll(/href="#([^"]+)"/g))assert.ok(fifthIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  assert.ok(fifthArticle.includes(`href="${entryUrl(fourthEntry)}/"`));
  const sixthEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch02-s1.md')!;
  assert.ok(sixthEntry);
  assert.equal(sixthEntry.mathFont,'cm-bea');
  assert.equal(sixthEntry.attachmentPath,'notes/real-functions-v1/real-functions-v1-2-1.pdf');
  assert.ok(html.includes(`href="${entryUrl(sixthEntry)}/"`));
  const sixthArticle=renderToStaticMarkup(createElement(Article,{entry:sixthEntry,items}));
  assert.doesNotMatch(sixthArticle,/katex-error/);
  const sixthIds=new Set([...sixthArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of sixthArticle.matchAll(/href="#([^"]+)"/g))assert.ok(sixthIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  assert.ok(sixthArticle.includes(`href="${entryUrl(fifthEntry)}/"`));
  assert.ok(fifthArticle.includes(`href="${entryUrl(sixthEntry)}/"`));
  const seventhEntry=items.find(e=>e.sourcePath==='notes/real-functions-v1/ch02-s2.md')!;
  assert.ok(seventhEntry);
  assert.equal(seventhEntry.mathFont,'cm-bea');
  assert.equal(seventhEntry.attachmentPath,'notes/real-functions-v1/real-functions-v1-2-2.pdf');
  assert.ok(html.includes(`href="${entryUrl(seventhEntry)}/"`));
  const seventhArticle=renderToStaticMarkup(createElement(Article,{entry:seventhEntry,items}));
  assert.doesNotMatch(seventhArticle,/katex-error/);
  const seventhIds=new Set([...seventhArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of seventhArticle.matchAll(/href="#([^"]+)"/g))assert.ok(seventhIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  assert.ok(seventhArticle.includes(`href="${entryUrl(sixthEntry)}/"`));
  assert.ok(sixthArticle.includes(`href="${entryUrl(seventhEntry)}/"`));
  assert.ok(seventhArticle.includes('href="/math/real-functions-v1/#section-2-3"'));
  const fourthArticle=renderToStaticMarkup(createElement(Article,{entry:fourthEntry,items}));
  assert.doesNotMatch(fourthArticle,/katex-error/);
  assert.ok(fourthArticle.includes(`href="${entryUrl(fifthEntry)}/"`));
  const fourthIds=new Set([...fourthArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of fourthArticle.matchAll(/href="#([^"]+)"/g))assert.ok(fourthIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  assert.ok(fourthArticle.includes(`href="${entryUrl(thirdEntry)}/"`));
  const thirdArticle=renderToStaticMarkup(createElement(Article,{entry:thirdEntry,items}));
  assert.doesNotMatch(thirdArticle,/katex-error/);
  assert.ok(thirdArticle.includes(`href="${entryUrl(fourthEntry)}/"`));
  const thirdIds=new Set([...thirdArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of thirdArticle.matchAll(/href="#([^"]+)"/g))assert.ok(thirdIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  for(const component of [createElement(MathNavigation,{}),createElement(StudyDirectory,{items})])
    assert.ok(renderToStaticMarkup(component).includes(`href="${realFunctionsV1Url}"`));
  const article=renderToStaticMarkup(createElement(Article,{entry,items}));
  assert.equal((article.match(/href="\/math\/real-functions-v1\/#chapter-1"/g)||[]).length,2);
  assert.match(article,/data-math-font="cm-bea"/);
  assert.doesNotMatch(article,/katex-error/);
  const ids=new Set([...article.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of article.matchAll(/href="#([^"]+)"/g))assert.ok(ids.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
  const nextArticle=renderToStaticMarkup(createElement(Article,{entry:nextEntry,items}));
  assert.doesNotMatch(nextArticle,/katex-error/);
  const nextIds=new Set([...nextArticle.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]));
  for(const [,href]of nextArticle.matchAll(/href="#([^"]+)"/g))assert.ok(nextIds.has(decodeURIComponent(href)),`Missing local anchor: ${href}`);
});
